// ── 压缩手段 ────────────────────────────────────────────────────────────────
// 1. 去掉与卡片标题重复的物品名做主语的句子开头（「银剑在随机生成武器中占比0.6%」→「随机武器中占 0.6%」）。
// 2. 把 wiki 的固定说法换成短说法：「在生成时获得一把X」→「携带」、
//    「在游戏开始时获得」→「开局携带」、「有 X 的概率为被诅咒的」→「X 被诅咒」。
// 3. 数字与中文之间补空格（和 item-summary.js 里 DESCRIPTION_ZH 的写法一致）。
//
// ── 手写译文 ────────────────────────────────────────────────────────────────
// wiki 上没有中文「生成」章节的条目（多半也没有中文页），这里按英文原文手写简明译文，
// 与 item-summary.js 的 DESCRIPTION_ZH 同样的做法。

// 卡片正文宽度约 30 字/行，超过这个长度就太占版面了
const GENERATION_MAX = 120
// 预算还剩这么多时才肯收下半截长句，免得只剩几个字的尾巴
const MIN_TAIL = 30

// 句末断句；换行也算断句——引子与列表条目各占一行，
// 只按句号断会把「以下情况下树会生成水果：」黏进下一句
const SENTENCE = /[^。！？\n]+[。！？]?/g
// 量词：紧跟物品名的「一把 / 一枚 / 一本」等，去掉物品名时一并去掉
const QUANT = '个枚把支份块本张条件根副'
// 生成时的祝福状态，判断某句是不是在讲 BUC
const BUC = '(?:[被受]?诅咒|未诅咒|[被受]?祝福)'

// 「以下情况下树会生成水果：」这类引子后面跟着的是被省略的列表，整句去掉更通顺
const LIST_LEAD_IN = /(以下|如下|下列|分别是|包括|其中)[^，。；]*$/

/** 数字与拉丁词两侧补空格：`生成时有90.5%的概率` → `生成时 90.5% 的概率` */
function padTokens(text) {
  return text
    .replace(/([一-龥])([0-9A-Za-z])/g, '$1 $2')
    .replace(/([0-9A-Za-z%)】])([一-龥])/g, '$1 $2')
    .replace(/[（(]\s+|\s+[）)]/g, m => m.trim())
    .replace(/\s{2,}/g, ' ')
}

// 概率的写法：分数带百分比说明（3/40（7.5%））、百分比（7.5%）、纯分数（1/6），
// 前面可能带「低于/约」这类修饰，括号里的百分比同样可能带（如「3/290（约1.03%）」）
const MOD = '(?:低于|不到|小于|少于|约|大约|高于|超过|大于|至少|最多)?'
const PROB = new RegExp(`${MOD}\\s*[\\d.]+\\s*\\/\\s*[\\d.]+\\s*（\\s*[^）]{0,12}%\\s*）|${MOD}\\s*[\\d.]+%|${MOD}\\s*[\\d.]+\\s*\\/\\s*[\\d.]+`)
const PROB_SRC = PROB.source

/** 概率里的分数换个写法：`3/40（7.5%）` → `7.5%`，没有百分比时保留原样 */
function percentOf(text) {
  const m = text.match(/[\d.]+\/[\d.]+（([^）]{0,12}%)）/)
  if (m) return m[1]
  const p = text.match(/[\d.]+%/)
  return p ? p[0] : ''
}

/** 物品名（中文名与别名）在句子里的匹配；卡片标题已经写了名字，句中重复的可以省掉 */
function nameAlternatives(item) {
  return [item.zhName, ...(item.aliases || [])]
    .filter(n => n && n.length >= 2)
    .map(n => n.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))
    .sort((a, b) => b.length - a.length)
}

/** 去掉句首那个与卡片标题重复的物品名（「银剑在随机生成武器中占比…」） */
function dropLeadingName(text, item) {
  for (const name of nameAlternatives(item)) {
    if (text.startsWith(name)) {
      const rest = text.slice(name.length)
      // 「X不会随机生成」里的 X 是主语，去掉就读不通了，保留
      if (/^不|^无法|^不能/.test(rest)) return text
      // 只在能接得上时才去掉：物品名后面是「在/的/可」等谓语或虚词。
      // 「会」不在其中：「小刀会在多种怪物的起始物品中出现」去掉主语就残缺了
      if (/^[在的可得无不被将已均也生]/.test(rest)) return rest
    }
  }
  return text
}

/**
 * 句中重复的物品名去掉。只有站在「携带/获得」这类泛动词后面时才省得掉
 * （「有 1/2 概率携带一把银剑」→「有 1/2 概率携带」）；
 * 跟在「是」后面时省掉会缺宾语（「通关奖励有 50% 概率是一枚反射护身符」），
 * 名字前面带附魔时省掉会丢信息（「开局携带 +0 武士刀」），这两种都保留。
 */
function dropInnerName(text, item) {
  const names = nameAlternatives(item)
  if (names.length === 0) return text
  return text.replace(
    new RegExp(`(携带|获得|有售|出售|产出)(?:了|一[${QUANT}]|若干)?(?:${names.join('|')})(?:作为(?:主|起始)?武器)?`, 'g'),
    '$1',
  )
}

/** 「A和B有 1/2 概率携带」里的并列连词换成顿号，省一个字也更清楚 */
function joinNames(text) {
  if (!/概率|携带|开局|有售/.test(text)) return text
  if (/和平|和谐|和尚|和气|温和|总和|饱和/.test(text)) return text
  return text.replace(/([一-龥]{2,8})和(?=[一-龥]{2,8}(?:有|在生成|生成时|也))/, '$1、')
}

// ── 句子级的压缩 ────────────────────────────────────────────────────────────

/**
 * 一段话逐句压缩。规则按顺序套用，物品名（alt）拼进正则里，
 * 让「随机生成的护身符有 3/40（7.5%）的概率是反射护身符」这种整句能一次吃完。
 */
function compactSentence(text, item) {
  const alt = nameAlternatives(item).join('|')
  // 「随机生成的护身符有3/40（7.5%）的概率是反射护身符」的整句形态：
  // 「是」后面必须真的跟着物品名，否则这就是在讲生成时的 BUC（「随机生成的复活护身符有9/10的概率是未诅咒的」）
  const rateTail = alt ? `(?:一[${QUANT}])?(?:${alt})` : `一[${QUANT}]`
  const rules = [
    // 随机生成率：「X在随机生成的武器中占比0.6%」→「随机武器中占 0.6%」
    [/^在?(?:所有|全部)?随机生成的?([^，。；]{0,8}?)中占(?:比为?|的?比例是)?/, '随机$1中占'],
    [new RegExp(`^随机生成的?([^，。；]{0,10}?)有(${PROB_SRC})的?(?:概率)?[为是]${rateTail}`), '随机$1中占 $2'],
    // 剩下「随机生成的X」一律收成「随机X」（上面那条没吃完的多半在讲 BUC）
    [/随机生成的/, '随机'],
    // 「X的相对生成率是3/25（12%）」→「随机生成率 12%」
    [/^的?相对生成率是/, '随机生成率 '],
    // 「（准确值是1/290）」这类精度补注卡片上放不下，而且会挡住下面概率规则的匹配
    [/（准确值[^）]*）/g, ''],
    // BUC：「生成时有90.5%的概率为被诅咒的，9%的概率为未诅咒的」→「生成时 90.5% 被诅咒的，9% 未诅咒的」
    // 只认后面跟祝福状态的那几句，否则「通关奖励有50%的概率是一枚X」会被拆散
    [new RegExp(`(${PROB_SRC})的?概率[为是](?=${BUC})`, 'g'), '$1 '],
    // 概率：「有1/2的概率」「有低于1%的概率」→「有 1/2 概率」
    [new RegExp(`有(${PROB_SRC})的?(?:基础)?概率`, 'g'), '有 $1 概率'],
    // 生成场合：「所有玩家怪物在生成时有…」→「所有玩家怪物有…」
    [/在生成时有/, '有'],
    // 上面那条把「在生成时有」吃掉后还剩「生成时有 1/2 …」的，收成「生成时 1/2 …」
    [/生成时有(?=(?:低于|不到|小于|少于|大约|约|高于|超过|大于)?\s*[\d.])/, '生成时 '],
    // 携带与开局
    [/(?:会|将)(?=开局)/, ''],
    [/在生成时(?:有(?:可能|概率))?(?:会)?(?:获得|携带)/, '携带'],
    [/在游戏开始时(?:会)?获得(?=的)/, '开局获得'],
    [/在游戏开始时(?:会)?(?:获得|拥有|携带)/, '开局携带'],
    [/在游戏开始时即?鉴定/, '开局即鉴定'],
    [/有概率(?:会)?(?:获得|携带)/, '有概率携带'],
    [/(?:则)?有可能(?:会)?(?:获得|携带)/, '有可能携带'],
    // wiki 有的句子写成「会携带X生成：」，X 去掉后剩下「携带生成」
    [/(携带|获得)(?=生成)/, '$1'],
    // 「有2/9的概率携带」里那个「的」，前面的规则没吃到时在这里收掉
    [new RegExp(`(${PROB_SRC})\\s*的\\s*(?=概率)`, 'g'), '$1 '],
    [/概率(?:会|能|可以)?(?:获得|携带)/, '概率携带'],
    [/生成时(?:会)?(?:获得|携带)/, '生成时携带'],
    // 「（准确值是1/290）」这类精度补注卡片上放不下
    [/（准确值[^）]*）/g, ''],
    // 「该物品生成时…」里的指代词可以省；「它们是X类怪物…」的「它们」省了就缺主语，不能动
    [/^(?:该物品|这件物品|该装备)/, ''],
    // 商店
    [/有(?:可能)?(?:会)?出售/, '可能有售'],
    [/必定(?:会)?出售/, '必定有售'],
    [/在(?:地)?面(?:上)?、?死亡掉落或商店中生成/, '地面/掉落/商店'],
  ]
  let out = dropLeadingName(text.trim(), item)
  for (const [re, to] of rules) out = out.replace(re, to)
  // 概率写成「分数（百分比）」时，讲生成率的句子里用百分比更直观，其余保留分数
  if (/中占|随机生成率/.test(out)) {
    const pct = percentOf(out)
    if (pct) out = out.replace(/[\d.]+\/[\d.]+（[^）]{0,12}%）/, pct)
  } else {
    out = out.replace(/([\d./]+)（[^）]{0,12}%）(?=\s*概率)/, '$1')
  }
  out = dropInnerName(out, item)
  out = joinNames(out)
  return out.replace(/\s{2,}/g, ' ').replace(/^[，、；]+/, '').replace(/[：:]$/, '').trim()
}

// ── 句子优先级 ──────────────────────────────────────────────────────────────
// 数字越大越先保留；压缩时从最低分的句子开始丢
const PRIORITY = [
  [/不会随机生成|无法随机生成|不能随机生成/, 100],
  // 「随机生成的护身符有3/40（7.5%）的概率是X」在压缩前也是这个写法，要一并认出来
  [/相对生成率|随机生成率|随机生成的?[^，。；]{0,10}中占|随机生成的?[^，。；]{0,10}有[\d.]/, 95],
  // 「由于没有这样的职业，该替换机制不会触发」这类空转说明，能用上的场合几乎没有。
  // 要排在「开局」「携带」前面：这种句子往往也带着这两个词，否则会被当成有用信息留下
  [/替换机制|不会触发|不会发生/, 20],
  [/开局|游戏开始时/, 80],
  [/携带|起始物品/, 75],
  [/必定|总是生成|特殊关卡|必定会生成/, 70],
  [/商店|有售/, 60],
  [/许愿|骨档|祈祷/, 55],
  [/被?诅咒|祝福|未受诅|充能|发数/, 50],
  [/丰饶之角/, 40],
]

function score(text) {
  for (const [re, s] of PRIORITY) if (re.test(text)) return s
  return 30
}

/** 一段话太长时在分句处断开，避免在词中间截断 */
function truncate(text, max) {
  const clean = text.replace(/\s+/g, ' ').trim()
  if (clean.length <= max) return clean
  const cut = clean.slice(0, max)
  const sentence = Math.max(...['。', '！', '？'].map(p => cut.lastIndexOf(p)))
  if (sentence > max / 2) return cut.slice(0, sentence + 1)
  const clause = Math.max(...['；', '，', '、'].map(p => cut.lastIndexOf(p)))
  if (clause > max / 2) return `${cut.slice(0, clause).replace(/[，、；]$/, '')}…`
  return `${cut}…`
}

/** 整理成一段：逐句压缩，超长时按优先级丢句子，仍超长就截断 */
function condenseGeneration(text, item, max = GENERATION_MAX) {
  if (!text) return ''
  const sentences = (text.match(SENTENCE) || [])
    .map(s => s.trim())
    .filter(Boolean)
    // wiki 有的句子本身就残缺（模板没填出数字），留着会在卡片上读不通
    .filter(s => !/约有的概率|\{\{|\}\}/.test(s))
    .map((raw, i) => {
      // 列表条目在抓取时已经丢掉，只留下以「：」收尾的引子。
      // 「以下情况下树会生成水果：」这类引子离开了列表就没有内容，整句去掉；
      // 「某些职业会在游戏开始时获得匕首：」本身说得通，去掉冒号当一句概括留下
      const lead = /[：:]\s*$/.test(raw)
      const body = lead ? raw.replace(/[：:]\s*$/, '') : raw
      return { i, lead, body, s: compactSentence(body, item), score: score(body) }
    })
    .filter(k => k.s && !(k.lead && LIST_LEAD_IN.test(k.body)))
  if (sentences.length === 0) return ''

  // 按优先级从高到低往预算里塞，塞不下的先跳过（可能还塞得下后面更短的）
  const kept = []
  let used = 0
  for (const k of [...sentences].sort((a, b) => b.score - a.score || a.i - b.i)) {
    if (used + k.s.length <= max) {
      kept.push(k)
      used += k.s.length
      continue
    }
    // 剩下的预算还够放小半句时，就收下这句最要紧的长句，交给 truncate 在分句处断开；
    // 否则宁可空着也不放半截话
    if (max - used >= MIN_TAIL) kept.push(k)
    break
  }

  // 引子去掉冒号后句尾就没有标点了，拼起来会把两句话粘成一句，这里补上
  let out = kept.sort((a, b) => a.i - b.i)
    .map(k => (/[。！？…]$/.test(k.s) ? k.s : `${k.s}。`))
    .join('')
  out = padTokens(out).replace(/[，、；]{2,}/g, '，').replace(/[，、；]+(?=[。；！？])/g, '')
  out = truncate(out, max)
  // 正好顶到上限时不再补句号，免得超出一个字
  if (out && out.length < max && !/[。！？…]$/.test(out)) out += '。'
  return out
}

