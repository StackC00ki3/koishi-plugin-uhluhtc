// ── 保留什么 ────────────────────────────────────────────────────────────────
// 玩家看这一段是为了回答「这东西上哪弄」。所以按下面的优先级保留句子，
// 超长时从优先级最低的开始丢（丢的时候保持句子原有的先后顺序，读起来仍是连贯的一段）：
//     不会随机生成 > 随机生成率 > 职业开局 / 怪物携带 > 必定生成的特殊地点
//     > 商店 > 许愿与骨档 > 生成时的 BUC 与充能 > 丰饶之角等次要来源
